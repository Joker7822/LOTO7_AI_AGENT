def protected(root):
    return {str(p.relative_to(root)): p.read_bytes() for p in (
        root / "loto7.csv",
        root / "loto7_agent_output/source_validation.json",
        root / "loto7_agent_output/model_champion.json",
        root / "loto7_agent_output/research_cycle_guard.json",
    )}


def test_open_ended_source_code_and_meta_policy_continue_across_checkpoints(root):
    before = protected(root)
    first = agent.cycle(root, steps=5)
    assert first["generations_total"] == 5
    assert first["execution_limits"]["global_generations"] is None
    assert first["execution_limits"]["global_trials"] is None
    assert first["execution_limits"]["requires_new_draw"] is False
    assert first["authority"]["production_predictions"] is False
    assert first["authority"]["autonomous_main_code_changes"] is False
    assert len(first["hall_of_fame"]) >= 1
    assert sum(v["trials"] for v in first["mutation_policy"].values()) == 5
    next_ = agent.cycle(root, steps=7)
    assert next_["generations_total"] == 12
    assert sum(v["trials"] for v in next_["mutation_policy"].values()) == 12
    assert next_["recorded_rounds"] == 155
    assert next_["independent_source_verified"] is False
    assert len(journal(root / "loto7_agent_output" / agent.LEDGER)) == 2
    assert protected(root) == before


def test_model_generated_python_code_executes_same_mathematical_strategy(root):
    v = agent.cycle(root, steps=6)
    generated = (root / "loto7_agent_output" / agent.PROGRAM).read_text()
    assert "AUTOGENERATED MATHEMATICAL RESEARCH CODE" in generated
    local = {}
    exec(compile(generated, "<generated-research>", "exec"), local)
    h, meta = history(root)
    expected = agent.predict_inclusion_probability(
        h[:-1], v["research_champion"]["expression"]
    )
    np.testing.assert_allclose(local["predict_inclusion_probability"](h[:-1]), expected)
    assert expected.sum() == pytest.approx(7, abs=1e-8)


