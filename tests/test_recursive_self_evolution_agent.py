def test_generated_math_and_cooccurrence_are_finite_after_int8_boundary():
    data = np.zeros((150, 37), dtype=np.int8)
    data[:, :7] = 1
    feat = agent.feature_vectors(data)
    assert feat["pair"].shape == (37,)
    for expr in ("uniform", "hot20", "pair", "tanh(gap + hot80)",
                 "sqrt(abs(hot20 - cold20) + 0.1)"):
        q = agent.expression_inclusion(feat, expr)
        assert np.all(np.isfinite(q))
        assert np.all((0 < q) & (q < 1))
        assert q.sum() == pytest.approx(7, abs=1e-8)


def test_reject_wrong_draws_and_invalid_math():
    bad = np.ones((110, 37), dtype=np.int8)
    with pytest.raises(ValueError, match="seven-of-37"):
        agent.feature_vectors(bad)
    correct = np.zeros((110, 37), dtype=np.int8)
    correct[:, :7] = 1
    feats = agent.feature_vectors(correct)
    with pytest.raises(ValueError, match="invalid scores"):
        agent.expression_inclusion(feats, "hot20 / (uniform - uniform)")
    with pytest.raises(ValueError, match="invalid scores"):
        agent.expression_inclusion(feats, "log1p(-(hot20 + uniform))")


def test_deterministic_regardless_of_hourly_slice_splits(root, tmp_path):
    alternate = tmp_path / "split"
    shutil.copytree(root, alternate)
    continuous = agent.cycle(root, steps=16)
    agent.cycle(alternate, steps=6)
    split = agent.cycle(alternate, steps=10)
    assert continuous["generations_total"] == split["generations_total"] == 16
    for field in ("research_champion", "hall_of_fame", "mutation_policy",
                  "mutation_probabilities"):
        assert continuous[field] == split[field]
    assert (root / "loto7_agent_output" / agent.PROGRAM).read_bytes() == (
        alternate / "loto7_agent_output" / agent.PROGRAM
    ).read_bytes()


def test_tampered_journal_or_checkpoint_refuses_unverifiable_resume(root):
    agent.cycle(root, steps=3)
    out = root / "loto7_agent_output"
    state = out / agent.STATE
    obj = json.loads(state.read_text())
    obj["mutation_policy"]["tune"]["trials"] += 9999
    state.write_text(json.dumps(obj))
    with pytest.raises(ValueError, match="differs from journal"):
        agent.cycle(root, steps=1)
    state.unlink()
    chain = out / agent.LEDGER
    record = json.loads(chain.read_text().splitlines()[0])
    record["snapshot"]["mutation_policy"]["tune"]["trials"] += 9999
    chain.write_text(json.dumps(record) + "\n")
    with pytest.raises(ValueError, match="hash chain corrupted"):
        agent.cycle(root, steps=1)


def test_crash_recovery_reconstructs_state_only_from_hashed_journal(root):
    first = agent.cycle(root, steps=3)
    out = root / "loto7_agent_output"
    (out / agent.STATE).unlink()
    recovered = agent.cycle(root, steps=4)
    assert recovered["generations_total"] == first["generations_total"] + 4
    assert recovered["last_record_sha256"] == journal(out / agent.LEDGER)[-1]["record_sha256"]


def test_meta_policy_updates_and_keeps_exploratory_mutation_probability(root):
    first = agent.cycle(root, steps=30)
    scores = first["mutation_probabilities"]
    assert set(scores) == set(agent.MOVES)
    assert sum(scores.values()) == pytest.approx(1, abs=1e-12)
    assert all(v > 0 for v in scores.values())
    assert len({agent.encoded(v["expression"]) for v in first["hall_of_fame"]}) == len(first["hall_of_fame"])
    assert sum(x["trials"] for x in first["mutation_policy"].values()) == 30


